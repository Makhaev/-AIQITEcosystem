import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
const [dir, nginxDir] = process.argv.slice(2);
if(!dir||!nginxDir)throw Error('usage: node scripts/r13-proxy-config.mjs RUN_DIR NGINX_DIR');
const root=process.cwd().replaceAll('\\','/'), output=resolve(dir).replaceAll('\\','/'), nginx=resolve(nginxDir).replaceAll('\\','/');
await mkdir(output,{recursive:true});
await mkdir(`${output}/logs`,{recursive:true});
await mkdir(`${output}/temp`,{recursive:true});
const tempNames=['client_body','proxy','fastcgi','uwsgi','scgi'];
for(const name of tempNames)await mkdir(`${output}/temp/${name}`,{recursive:true});
const tempPaths=tempNames.map(name=>`${name}_temp_path "${output}/temp/${name}";`).join('\n');
const http=await readFile('frontend/nginx-http.conf','utf8'), original=await readFile('frontend/nginx-server.conf','utf8');
const sink=process.platform==='win32'?'nul':'/dev/null';
const mime=process.platform==='win32'?`${nginx}/conf/mime.types`:`${nginx}/mime.types`;
const server=original.replace('root /usr/share/nginx/html;',`root "${root}/frontend/dist";`).replaceAll('http://backend:8080','http://127.0.0.1:18180').replace('/dev/stdout',`"${output}/access.log"`).replace('/dev/null',sink);
await writeFile(`${output}/server.conf`,server);
await writeFile(`${output}/nginx.conf`,`worker_processes 1;\npid "${output}/nginx.pid";\nerror_log ${sink};\nevents {worker_connections 1024;}\nhttp {\ninclude "${mime}";\ndefault_type application/octet-stream;\n${tempPaths}\n${http}\nserver {listen 127.0.0.1:14173; include "${output}/server.conf";}\n}\n`);
await writeFile(`${output}/source.json`,JSON.stringify({server_fragment_sha256:createHash('sha256').update(original).digest('hex'),http_fragment_sha256:createHash('sha256').update(http).digest('hex'),changes:['filesystem roots, logs and temporary directories','loopback upstream 18180','listen loopback 14173',`error sink ${sink}`]},null,2));
