import { expect, test, type Page } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

const password = process.env.M2_TEST_PASSWORD!;
const origin = 'http://127.0.0.1:15173';
async function login(page: Page, role: string) {
  await page.goto('/#/account');
  const logout = page.getByRole('button', { name: 'Выйти', exact: true });
  await expect(page.getByRole('heading').first()).toBeVisible();
  if (await logout.count()) await logout.click();
  await expect(page.getByRole('heading', { name: 'Вход в AIQ Core' })).toBeVisible();
  await page.getByLabel('Email', { exact: true }).fill(`${role}@example.test`);
  await page.getByLabel('Пароль', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Выйти', exact: true })).toBeVisible();
}
async function api(page: Page, path: string, body?: unknown) {
  const csrf = await (await page.request.get('/api/v1/auth/csrf')).json();
  const response = body === undefined ? await page.request.get(`/api/v1${path}`) : await page.request.post(`/api/v1${path}`, { data: body, headers: { Origin: origin, 'X-CSRF-Token': csrf.csrf_token } });
  expect(response.ok(), `HTTP ${response.status()} ${path}`).toBeTruthy();
  return response.json();
}
async function fit(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
  const violations = (await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations;
  expect(violations.map(v => `${v.id}: ${v.description}`)).toEqual([]);
}
async function confirm(page: Page, button: string) {
  await page.getByRole('button', { name: button, exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Подтвердить', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
}

